WIDTH = 5
HEIGHT = 7


def measure(word, scale=1, tracking=1):
    """Pixel width of `word` when drawn at `scale`."""
    if not word:
        return 0

    return (len(word) * (WIDTH + tracking) - tracking) * scale


def draw(img, word, x, y, color, scale=1, tracking=1):
    """Stamp `word` onto an RGBA image, top-left anchored at (x, y)."""
    px = img.load()
    w, h = img.size
    cx = x

    for ch in word.upper():
        rows = GLYPHS.get(ch, GLYPHS[' ']).split('|')

        for ry, row in enumerate(rows):
            for rx, cell in enumerate(row):
                if cell != '#':
                    continue

                for sy in range(scale):
                    for sx in range(scale):
                        ix = cx + rx * scale + sx
                        iy = y + ry * scale + sy

                        if 0 <= ix < w and 0 <= iy < h:
                            px[ix, iy] = color

        cx += (WIDTH + tracking) * scale


def centered(img, word, y, color, scale=1, tracking=1, cx=None):
    """Same as draw(), horizontally centred on `cx` (default: image centre)."""
    if cx is None:
        cx = img.size[0] // 2

    draw(img, word, cx - measure(word, scale, tracking) // 2, y, color,
         scale, tracking)


def stamp(word, color, scale=1, tracking=1):
    """A tight RGBA image of `word`, for compositing with effects."""
    img = Image.new('RGBA', (measure(word, scale, tracking),
                             HEIGHT * scale), (0, 0, 0, 0))
    draw(img, word, 0, 0, color, scale, tracking)
    return img
